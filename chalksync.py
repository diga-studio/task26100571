"""ChalkSync: layer-clear and timed-undo CRDT kernel (stdlib only).

Up to 16 replicas, two fixed layers (0 and 1). Replicas exchange only
JSON-serializable events produced by ``emit``; no shared state.

Causality is tracked with a version vector: every event carries the
per-author sequence numbers its author had observed when it was created.
A clear covers exactly the adds on its layer that lie in its causal past,
so no per-stroke target list is ever needed and event size stays bounded.
"""

from __future__ import annotations

import copy
import json

LAYERS = (0, 1)
MAX_REPLICAS = 16
UNDO_WINDOW_MS = 10_000

_OP_ADD = "add"
_OP_CLEAR = "clear"
_OP_UNDO = "undo"


def _check_layer(layer: int) -> None:
    if layer not in LAYERS:
        raise ValueError(f"unknown layer: {layer!r}")


class Replica:
    """One ChalkSync replica. Replicas exchange only serialized events."""

    def __init__(self, author: str) -> None:
        if not author:
            raise ValueError("author id must be non-empty")
        self.author = str(author)
        self._seq = 0  # next local sequence number is _seq + 1
        # applied[author] = highest contiguous applied seq for that author
        self._applied: dict[str, int] = {}
        self._buffer: list[dict] = []  # received but predecessors missing
        self._seen: set[tuple[str, int]] = set()
        # Per-layer applied state, updated incrementally (never replayed).
        self._adds: dict[int, list[dict]] = {layer: [] for layer in LAYERS}
        self._clears: dict[int, list[dict]] = {layer: [] for layer in LAYERS}
        self._undone: set[tuple[str, int]] = set()  # (author, seq) of clears
        # Local-only bookkeeping: emission time of this replica's clears.
        self._clear_times: dict[int, int] = {}

    # ---------------------------------------------------------------- emit

    def emit(self, action: dict, now_ms: int) -> dict | None:
        """Execute a local add/clear/undo; return a JSON-serializable event.

        ``action`` is one of:
          {"op": "add",   "layer": L, "content": ...}
          {"op": "clear", "layer": L}
          {"op": "undo",  "target": <seq of a clear emitted by this replica>}

        Returns None when the action is rejected (undo at/after the 10s
        window, or undo of a clear not generated here); state is unchanged.
        """
        op = action.get("op")
        if op == _OP_ADD:
            _check_layer(action["layer"])
            content = copy.deepcopy(action["content"])
            json.dumps(content)  # content must be JSON-serializable
            event = self._new_event({_OP_ADD: True})
            event["layer"] = action["layer"]
            event["content"] = content
            event["stroke"] = f"{self.author}:{event['s']}"
        elif op == _OP_CLEAR:
            _check_layer(action["layer"])
            event = self._new_event({_OP_CLEAR: True})
            event["layer"] = action["layer"]
            self._clear_times[event["s"]] = now_ms
        elif op == _OP_UNDO:
            target = action["target"]
            if isinstance(target, dict):  # accept the clear event itself
                target = target.get("s") if target.get("a") == self.author else None
            if target not in self._clear_times:
                return None  # not a clear generated by this replica
            if now_ms - self._clear_times[target] >= UNDO_WINDOW_MS:
                return None  # outside the window; exactly 10000 ms rejected
            event = self._new_event({_OP_UNDO: True})
            event["target"] = target
        else:
            raise ValueError(f"unknown op: {op!r}")
        self._apply(event)
        return copy.deepcopy(event)

    def _new_event(self, fields: dict) -> dict:
        self._seq += 1
        event = {
            "a": self.author,
            "s": self._seq,
            # Causal predecessors: own prior events (implied by "s") plus
            # every other author's events observed so far.
            "d": {a: n for a, n in self._applied.items()
                  if a != self.author and n > 0},
        }
        event.update(fields)
        return event

    # -------------------------------------------------------------- receive

    def receive(self, event: dict) -> None:
        """Accept an event produced by some replica's emit().

        Tolerates duplicates, arbitrary delay and reordering. Events whose
        causal predecessors are missing are buffered and have no effect
        until the gap is filled.
        """
        key = (event["a"], event["s"])
        if key in self._seen:
            return
        self._seen.add(key)
        self._buffer.append(dict(event))
        self._drain()

    def _ready(self, event: dict) -> bool:
        if self._applied.get(event["a"], 0) != event["s"] - 1:
            return False
        return all(self._applied.get(a, 0) >= n
                   for a, n in event["d"].items())

    def _drain(self) -> None:
        progress = True
        while progress:
            progress = False
            for event in sorted(self._buffer,
                                key=lambda e: (e["a"], e["s"])):
                if self._ready(event):
                    self._buffer.remove(event)
                    self._apply(event)
                    progress = True
                    break

    def _apply(self, event: dict) -> None:
        author, seq = event["a"], event["s"]
        self._applied[author] = seq
        if _OP_ADD in event:
            self._adds[event["layer"]].append(event)
        elif _OP_CLEAR in event:
            self._clears[event["layer"]].append(event)
        elif _OP_UNDO in event:
            self._undone.add((author, event["target"]))
        else:  # pragma: no cover - emit only produces the three kinds
            raise ValueError("malformed event")

    # -------------------------------------------------------------- visible

    @staticmethod
    def _in_causal_past(add: dict, later: dict) -> bool:
        """True iff `add` was observed by the author of `later` beforehand."""
        author, seq = add["a"], add["s"]
        if author == later["a"]:
            return seq < later["s"]
        return later["d"].get(author, 0) >= seq

    def visible(self, layer: int) -> list:
        """Return currently visible (stroke_id, content) pairs for a layer.

        A stroke is visible iff its add is applied and no applied,
        un-undone clear covers it. Output order is canonical (sorted by
        stroke id), so replicas holding the same events agree exactly.
        """
        _check_layer(layer)
        active_clears = [c for c in self._clears[layer]
                         if (c["a"], c["s"]) not in self._undone]
        result = []
        for add in self._adds[layer]:
            if not any(self._in_causal_past(add, c) for c in active_clears):
                result.append((add["stroke"], copy.deepcopy(add["content"])))
        result.sort(key=lambda pair: pair[0])
        return result
